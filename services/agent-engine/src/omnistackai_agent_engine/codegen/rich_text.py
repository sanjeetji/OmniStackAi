"""PC-104: rich text in generated apps - one allowlist, enforced on every write, applied again on display.

A ``rich_text`` field holds HTML written with the tiptap editor (headings, bold, italic, lists,
quotes, links, code). Every backend cleans it on create and update with a proven allowlist
sanitizer - Python ``nh3`` (ammonia), Go ``bluemonday``, Node ``sanitize-html`` - so a script, an
event handler, a style or a ``javascript:`` link can never be stored, whoever calls the API. The
web and admin apps sanitize again with DOMPurify before rendering; tables and the mobile app show
plain text.
"""

from __future__ import annotations

import json

from ..application_ir import ApplicationIR, Entity, FieldType

#: What formatted text may contain - and nothing else.
TAGS: tuple[str, ...] = ("p", "br", "strong", "b", "em", "i", "u", "s", "h2", "h3", "h4", "ul", "ol", "li",
                         "blockquote", "code", "pre", "hr", "a")
LINK_ATTRIBUTES: tuple[str, ...] = ("href", "title", "target")
URL_SCHEMES: tuple[str, ...] = ("http", "https", "mailto")

#: The editor and the second sanitizing pass on display (React 18 compatible).
RICH_TEXT_LIBRARIES: dict[str, str] = {
    "@tiptap/react": "3.31.3",
    "@tiptap/pm": "3.31.3",
    "@tiptap/starter-kit": "3.31.3",
    "dompurify": "3.4.16",
}
PYTHON_REQUIREMENT = "nh3==0.3.7"
GO_REQUIRE = "github.com/microcosm-cc/bluemonday v1.0.27"
NODE_DEPENDENCY = ("sanitize-html", "^2.17.7")
NODE_TYPES = ("@types/sanitize-html", "^2.16.0")


#: Words in a prompt that ask for formatting (PC-104, found live: a built-in template planned an
#: article's body as plain text although the prompt asked for "headings, lists, links").
_FORMATTING_CUES = ("formatted", "formatting", "rich text", "rich-text", "wysiwyg", "markdown", "headings",
                    "bold", "bullet", "lists", "editor")
_LONG_CONTENT_NAMES = frozenset({"body", "content", "description", "notes", "article", "details", "about", "bio"})


def with_rich_text(ir: ApplicationIR, prompt: str) -> ApplicationIR:
    """When the prompt asks for formatting, long text fields named for content become rich text.

    Deterministic, and only for the cues above: a plain-text body stays plain unless formatting
    was asked for. A plan (from the model or a template) that already says rich_text is unchanged.
    """
    from dataclasses import replace

    text = (prompt or "").lower()
    if not any(cue in text for cue in _FORMATTING_CUES):
        return ir
    entities = []
    changed = False
    for entity in ir.entities:
        fields = []
        for field in entity.fields:
            if field.type is FieldType.TEXT and field.name in _LONG_CONTENT_NAMES and entity.name.lower() != "comment":
                field = replace(field, type=FieldType.RICH_TEXT)
                changed = True
            fields.append(field)
        entities.append(replace(entity, fields=tuple(fields)))
    return replace(ir, entities=tuple(entities)) if changed else ir


def rich_fields(entity: Entity) -> list[str]:
    return [field.name for field in entity.fields if field.type is FieldType.RICH_TEXT]


def has_rich_text(ir: ApplicationIR) -> bool:
    return any(rich_fields(entity) for entity in ir.entities)


# ── Python (FastAPI / Pydantic) ─────────────────────────────────────────────────────────────────

def python_module() -> str:
    tags = ", ".join(repr(t) for t in TAGS)
    return f'''"""Formatted text is cleaned before it is stored (generated by OmniStackAI, PC-104).

Only these tags survive; links keep http, https and mailto addresses and open safely. Scripts,
event handlers, styles and javascript: links are removed, whoever calls the API.
"""
from __future__ import annotations

import nh3

TAGS = {{{tags}}}
ATTRIBUTES = {{"a": {{{", ".join(repr(a) for a in LINK_ATTRIBUTES)}}}}}
URL_SCHEMES = {{{", ".join(repr(s) for s in URL_SCHEMES)}}}


def clean_html(value: object) -> object:
    if value is None or not isinstance(value, str):
        return value
    return nh3.clean(value, tags=TAGS, attributes=ATTRIBUTES, url_schemes=URL_SCHEMES,
                     link_rel="noopener noreferrer nofollow", strip_comments=True)
'''


def python_validator(fields: list[str]) -> list[str]:
    names = ", ".join(repr(name) for name in fields)
    return [
        "",
        f"    @field_validator({names}, mode=\"before\")",
        "    @classmethod",
        "    def _clean_rich_text(cls, value: object) -> object:",
        "        # PC-104: formatted text is cleaned on every create and update.",
        "        return clean_html(value)",
    ]


# ── Go ─────────────────────────────────────────────────────────────────────────────────────────

def go_policy() -> str:
    tags = ", ".join(f'"{t}"' for t in TAGS if t != "a")
    return (
        "// PC-104: formatted text is cleaned before it is stored. Only these tags survive; links keep\n"
        "// http, https and mailto addresses. Scripts, event handlers and styles are removed.\n"
        "var richTextPolicy = func() *bluemonday.Policy {\n"
        "\tp := bluemonday.NewPolicy()\n"
        f"\tp.AllowElements({tags})\n"
        '\tp.AllowAttrs("href", "title", "target").OnElements("a")\n'
        '\tp.AllowURLSchemes("http", "https", "mailto")\n'
        "\tp.RequireNoFollowOnLinks(true)\n"
        "\tp.RequireNoReferrerOnLinks(true)\n"
        "\tp.AddTargetBlankToFullyQualifiedLinks(true)\n"
        "\treturn p\n"
        "}()\n"
    )


def go_sanitize_method(entity: Entity, pascal) -> str:
    lines = [f"// SanitizeRichText cleans {entity.name}'s formatted text (PC-104).",
             f"func (m *{entity.name}) SanitizeRichText() {{"]
    for field in entity.fields:
        if field.type is not FieldType.RICH_TEXT:
            continue
        name = pascal(field.name)
        if field.required:
            lines.append(f"\tm.{name} = richTextPolicy.Sanitize(m.{name})")
        else:
            lines.append(f"\tif m.{name} != nil {{\n\t\tclean := richTextPolicy.Sanitize(*m.{name})\n\t\tm.{name} = &clean\n\t}}")
    lines.append("}")
    return "\n".join(lines) + "\n"


# ── Node (zod) ───────────────────────────────────────────────────────────────────────────────────

def node_prelude() -> str:
    return (
        "import sanitizeHtml from 'sanitize-html';\n\n"
        "// PC-104: formatted text is cleaned on every create and update, whoever calls the API.\n"
        "const RICH_TEXT: sanitizeHtml.IOptions = {\n"
        f"  allowedTags: {json.dumps(list(TAGS))},\n"
        # rel is allowed only because the transform below always sets it to the safe value.
        f"  allowedAttributes: {{ a: {json.dumps([*LINK_ATTRIBUTES, 'rel'])} }},\n"
        f"  allowedSchemes: {json.dumps(list(URL_SCHEMES))},\n"
        "  transformTags: { a: sanitizeHtml.simpleTransform('a', { rel: 'noopener noreferrer nofollow' }) },\n"
        "};\n"
        "const cleanRichText = (value: string) => sanitizeHtml(value, RICH_TEXT);\n\n"
    )


