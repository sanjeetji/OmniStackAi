RICH_TEXT_EDITOR = r'''"use client";

// Generated by OmniStackAI (PC-104): the editor for formatted text. It produces HTML, which the
// API cleans with an allowlist before storing it; <RichText> cleans it again before showing it.
import { useEffect, useRef } from "react";
import { EditorContent, useEditor } from "@tiptap/react";
import StarterKit from "@tiptap/starter-kit";
import {
  Bold, Code, Heading2, Heading3, Italic, Link as LinkIcon, List, ListOrdered, Quote, Redo2, Strikethrough, Undo2,
} from "lucide-react";

export interface RichTextEditorProps {
  value: string;
  onChange: (html: string) => void;
  placeholder?: string;
  disabled?: boolean;
  /** For a <label htmlFor>. */
  id?: string;
}

// Created once: tiptap rebuilds the whole editor when its extensions change, and a new
// StarterKit on every render (found live) reset the text and dropped focus after each keystroke.
const EXTENSIONS = [StarterKit.configure({ heading: { levels: [2, 3] }, link: { openOnClick: false, autolink: true } })];

export function RichTextEditor({ value, onChange, placeholder, disabled, id }: RichTextEditorProps) {
  const emitted = useRef<string | null>(null);
  const produced = useRef<Set<string>>(new Set());
  // The latest onChange, read by the editor's update handler without rebuilding the editor.
  const onChangeRef = useRef(onChange);
  onChangeRef.current = onChange;
  const editor = useEditor({
    extensions: EXTENSIONS,
    content: value || "",
    editable: !disabled,
    immediatelyRender: false, // Next renders on the server first; the editor starts in the browser
    editorProps: {
      attributes: {
        ...(id ? { id } : {}),
        "aria-label": placeholder || "Formatted text",
        class: "rich-text min-h-[140px] px-3 py-2 text-sm outline-none",
      },
    },
    onUpdate: ({ editor: current }) => {
      // The editor keeps an empty line at the end for typing; it is not part of the text.
      const html = current.isEmpty ? "" : current.getHTML().replace(/(<p><\/p>)+$/, "");
      emitted.current = html;
      produced.current.add(html);
      if (produced.current.size > 200) produced.current = new Set([html]);
      onChangeRef.current(html);
    },
  }, []);

  // A form that loads a record after the editor opened (an edit form) hands it the stored text.
  // Found live: a form can re-render with a value a keystroke or two older than the editor's, and
  // loading it reset the editor - text typed after a toolbar click vanished. Only a value the
  // editor never produced itself (a record arriving from the API) is loaded.
  useEffect(() => {
    if (!editor || value === emitted.current || produced.current.has(value)) return;
    emitted.current = value;
    editor.commands.setContent(value || "", { emitUpdate: false });
  }, [editor, value]);

  const button = (label: string, active: boolean, run: () => void, Icon: typeof Bold) => (
    // onMouseDown: a click must not take focus (and the selection) from the text being formatted -
    // found live, text typed after a toolbar click was lost. Keyboard users still tab to it.
    <button key={label} type="button" onMouseDown={(event) => event.preventDefault()} onClick={run}
      disabled={disabled || !editor} aria-label={label} title={label}
      aria-pressed={active}
      className={`rounded p-1.5 ${active ? "bg-muted text-foreground" : "text-muted-foreground hover:bg-muted hover:text-foreground"}`}>
      <Icon className="h-4 w-4" aria-hidden />
    </button>
  );

  const link = () => {
    if (!editor) return;
    const previous = editor.getAttributes("link").href as string | undefined;
    const href = window.prompt("Link address (https://...)", previous || "https://");
    if (href === null) return;
    if (href === "" || href === "https://") editor.chain().focus().unsetLink().run();
    else editor.chain().focus().setLink({ href }).run();
  };

  return (
    <div className="overflow-hidden rounded-md border bg-background focus-within:border-primary focus-within:ring-2 focus-within:ring-primary/20">
      <div className="flex flex-wrap gap-0.5 border-b bg-muted/40 px-1.5 py-1" role="toolbar" aria-label="Formatting">
        {editor && [
          button("Bold", editor.isActive("bold"), () => editor.chain().focus().toggleBold().run(), Bold),
          button("Italic", editor.isActive("italic"), () => editor.chain().focus().toggleItalic().run(), Italic),
          button("Strikethrough", editor.isActive("strike"), () => editor.chain().focus().toggleStrike().run(), Strikethrough),
          button("Heading", editor.isActive("heading", { level: 2 }), () => editor.chain().focus().toggleHeading({ level: 2 }).run(), Heading2),
          button("Subheading", editor.isActive("heading", { level: 3 }), () => editor.chain().focus().toggleHeading({ level: 3 }).run(), Heading3),
          button("Bulleted list", editor.isActive("bulletList"), () => editor.chain().focus().toggleBulletList().run(), List),
          button("Numbered list", editor.isActive("orderedList"), () => editor.chain().focus().toggleOrderedList().run(), ListOrdered),
          button("Quote", editor.isActive("blockquote"), () => editor.chain().focus().toggleBlockquote().run(), Quote),
          button("Code", editor.isActive("codeBlock"), () => editor.chain().focus().toggleCodeBlock().run(), Code),
          button("Link", editor.isActive("link"), link, LinkIcon),
          button("Undo", false, () => editor.chain().focus().undo().run(), Undo2),
          button("Redo", false, () => editor.chain().focus().redo().run(), Redo2),
        ]}
      </div>
      <EditorContent editor={editor} />
    </div>
  );
}
'''

RICH_TEXT_VIEW = r'''"use client";

// Generated by OmniStackAI (PC-104): shows formatted text. The API already cleaned it; this cleans
// it again (DOMPurify, the same allowlist) so nothing a browser would run is ever rendered.
import { useEffect, useState } from "react";

const ALLOWED_TAGS = __TAGS__;
const ALLOWED_ATTR = ["href", "title", "target", "rel"];

/** The words without the formatting - for tables, previews and search results. */
export function plainText(html: unknown, max = 0): string {
  // Block tags separate words; inline ones (<strong>, <a>) do not (PC-108: "same day ." read oddly).
  const text = typeof html === "string" ? html.replace(/<\/?(p|h[1-6]|li|ul|ol|blockquote|pre|div|br)\b[^>]*>/gi, " ")
    .replace(/<[^>]*>/g, "").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/\s+/g, " ").trim() : "";
  return max > 0 && text.length > max ? `${text.slice(0, max).trimEnd()}...` : text;
}

export function RichText({ html, className = "" }: { html: unknown; className?: string }) {
  const [clean, setClean] = useState<string | null>(null);
  useEffect(() => {
    let alive = true;
    import("dompurify").then(({ default: DOMPurify }) => {
      if (!alive) return;
      DOMPurify.addHook("afterSanitizeAttributes", (node) => {
        if (node.tagName === "A") { node.setAttribute("rel", "noopener noreferrer nofollow"); node.setAttribute("target", "_blank"); }
      });
      setClean(DOMPurify.sanitize(typeof html === "string" ? html : "", { ALLOWED_TAGS, ALLOWED_ATTR, ALLOWED_URI_REGEXP: /^(?:https?:|mailto:)/i }));
      DOMPurify.removeHook("afterSanitizeAttributes");
    });
    return () => { alive = false; };
  }, [html]);
  if (typeof html !== "string" || !html) return <span className="text-muted-foreground">—</span>;
  // Until the sanitizer has loaded (and on the server), show the words only.
  if (clean === null) return <div className={`rich-text ${className}`}>{plainText(html)}</div>;
  return <div className={`rich-text ${className}`} dangerouslySetInnerHTML={{ __html: clean }} />;
}
'''.replace("__TAGS__", json.dumps(list(TAGS)))

