_PY_STORAGE = '''"""Where uploaded files live (generated by OmniStackAI, PC-102).

S3-compatible storage when S3_BUCKET, S3_ACCESS_KEY_ID and S3_SECRET_ACCESS_KEY are set -
Cloudflare R2 (S3_ENDPOINT=https://<account>.r2.cloudflarestorage.com) or AWS S3 (S3_REGION) -
otherwise the local disk (LOCAL_STORAGE_DIR, default ./uploads). STORAGE_DRIVER=s3 or local forces
one. Keys are never logged.
"""
from __future__ import annotations

import os
import shutil
from pathlib import Path
from typing import BinaryIO


def _env(name: str) -> str:
    return os.environ.get(name, "").strip()


class LocalStore:
    kind = "local"

    def __init__(self, root: str) -> None:
        self.root = Path(root).expanduser().resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def path(self, key: str) -> Path:
        target = (self.root / key).resolve()
        if self.root not in target.parents:
            raise ValueError("invalid_key")
        return target

    def put(self, key: str, data: BinaryIO, content_type: str) -> None:
        target = self.path(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, "wb") as out:
            shutil.copyfileobj(data, out)

    def exists(self, key: str) -> bool:
        return self.path(key).is_file()


class S3Store:
    kind = "s3"

    def __init__(self) -> None:
        import boto3
        from botocore.config import Config

        endpoint = _env("S3_ENDPOINT") or None
        self.bucket = _env("S3_BUCKET")
        # The app's folder in a shared bucket (set by the platform; empty for a bucket of its own).
        self.prefix = _env("STORAGE_PREFIX").strip("/")
        self.client = boto3.client(
            "s3",
            endpoint_url=endpoint,
            region_name=_env("S3_REGION") or ("auto" if endpoint else "us-east-1"),
            aws_access_key_id=_env("S3_ACCESS_KEY_ID"),
            aws_secret_access_key=_env("S3_SECRET_ACCESS_KEY"),
            config=Config(signature_version="s3v4", retries={"max_attempts": 3, "mode": "standard"}),
        )

    def _key(self, key: str) -> str:
        return f"{self.prefix}/{key}" if self.prefix else key

    def put(self, key: str, data: BinaryIO, content_type: str) -> None:
        self.client.upload_fileobj(data, self.bucket, self._key(key), ExtraArgs={"ContentType": content_type})

    def exists(self, key: str) -> bool:
        try:
            self.client.head_object(Bucket=self.bucket, Key=self._key(key))
            return True
        except Exception:  # noqa: BLE001 - missing and forbidden both mean "cannot serve it"
            return False

    def signed_url(self, key: str, filename: str, content_type: str, inline: bool, seconds: int = 300) -> str:
        disposition = "inline" if inline else "attachment"
        return self.client.generate_presigned_url(
            "get_object",
            Params={
                "Bucket": self.bucket,
                "Key": self._key(key),
                "ResponseContentType": content_type,
                "ResponseContentDisposition": f\'{disposition}; filename="{filename}"\',
            },
            ExpiresIn=seconds,
        )


_store: LocalStore | S3Store | None = None


def get_store() -> LocalStore | S3Store:
    global _store
    if _store is None:
        driver = (_env("STORAGE_DRIVER") or "auto").lower()
        s3_ready = all(_env(name) for name in ("S3_BUCKET", "S3_ACCESS_KEY_ID", "S3_SECRET_ACCESS_KEY"))
        if driver == "s3" or (driver == "auto" and s3_ready):
            if not s3_ready:
                raise RuntimeError("storage_not_configured: S3_BUCKET, S3_ACCESS_KEY_ID and S3_SECRET_ACCESS_KEY")
            _store = S3Store()
        else:
            _store = LocalStore(_env("LOCAL_STORAGE_DIR") or "./uploads")
    return _store
'''


_PY_CHECKS = '''"""Is this file what its name says? (generated by OmniStackAI, PC-102)

The name and the browser's declared type are both chosen by the sender, so neither is trusted:
the first bytes are, and for Office and OpenDocument files the parts inside the archive.
"""
from __future__ import annotations

import zipfile
from typing import BinaryIO

_OLE = bytes.fromhex("d0cf11e0a1b11ae1")
_FTYP_IMAGE = {"heic": {b"heic", b"heix", b"mif1", b"msf1", b"hevc", b"heim", b"heis"}, "avif": {b"avif", b"avis"}}
_OPEN_DOCUMENT = {
    "odt": b"application/vnd.oasis.opendocument.text",
    "ods": b"application/vnd.oasis.opendocument.spreadsheet",
    "odp": b"application/vnd.oasis.opendocument.presentation",
}
_OFFICE_PART = {"docx": "word/document.xml", "xlsx": "xl/workbook.xml", "pptx": "ppt/presentation.xml"}


def _zip_names(data: BinaryIO) -> set[str] | None:
    try:
        data.seek(0)
        with zipfile.ZipFile(data) as archive:
            return set(archive.namelist())
    except (zipfile.BadZipFile, OSError, ValueError):
        return None


def _text(head: bytes) -> bool:
    if b"\\x00" in head:
        return False
    try:
        head.decode("utf-8")
        return True
    except UnicodeDecodeError as error:
        # A multi-byte character cut at the end of the sample is still text.
        return error.start >= len(head) - 3


def matches(extension: str, data: BinaryIO) -> bool:
    data.seek(0)
    head = data.read(8192)
    data.seek(0)
    ext = extension.lower()
    brand = head[8:12]
    if ext in ("jpg", "jpeg"):
        return head.startswith(b"\\xff\\xd8\\xff")
    if ext == "png":
        return head.startswith(b"\\x89PNG\\r\\n\\x1a\\n")
    if ext == "gif":
        return head[:6] in (b"GIF87a", b"GIF89a")
    if ext == "webp":
        return head[:4] == b"RIFF" and head[8:12] == b"WEBP"
    if ext in _FTYP_IMAGE:
        return head[4:8] == b"ftyp" and brand in _FTYP_IMAGE[ext]
    if ext in ("mp4", "mov", "m4a"):
        images = set().union(*_FTYP_IMAGE.values())
        return head[4:8] == b"ftyp" and brand not in images
    if ext == "webm":
        return head.startswith(b"\\x1a\\x45\\xdf\\xa3")
    if ext == "ogg":
        return head.startswith(b"OggS")
    if ext == "mp3":
        return head.startswith(b"ID3") or (len(head) > 1 and head[0] == 0xFF and (head[1] & 0xE0) == 0xE0)
    if ext == "wav":
        return head[:4] == b"RIFF" and head[8:12] == b"WAVE"
    if ext == "pdf":
        return b"%PDF-" in head[:1024]
    if ext in ("doc", "xls", "ppt"):
        return head.startswith(_OLE)
    if ext == "rtf":
        return head.startswith(b"{\\\\rtf")
    if ext in ("txt", "csv"):
        return _text(head)
    if ext == "dcm":
        return head[128:132] == b"DICM"
    if ext in _OFFICE_PART or ext in _OPEN_DOCUMENT or ext == "zip":
        if not head.startswith(b"PK"):
            return False
        names = _zip_names(data)
        data.seek(0)
        if names is None:
            return False
        if any(name.lower().endswith("vbaproject.bin") for name in names):
            return False  # macros: a .docx never carries them, a renamed .docm does
        if ext in _OFFICE_PART:
            return _OFFICE_PART[ext] in names
        if ext in _OPEN_DOCUMENT:
            try:
                data.seek(0)
                with zipfile.ZipFile(data) as archive:
                    return archive.read("mimetype").strip() == _OPEN_DOCUMENT[ext]
            except (KeyError, zipfile.BadZipFile, OSError):
                return False
            finally:
                data.seek(0)
        return True
    return False
'''


_PY_ROUTER = '''"""Uploads and downloads (generated by OmniStackAI, PC-102).

POST /uploads takes one file for one field ("Entity.field"), checks it against that field's
policy - extension, real content and size - and stores it. GET /files/<key> serves it: a
short-lived signed link from S3-compatible storage, or the file itself from the local disk.
"""
from __future__ import annotations

import re
import tempfile
import uuid

from fastapi import APIRouter, File, Form, HTTPException, Query, UploadFile
from fastapi.concurrency import run_in_threadpool
from fastapi.responses import FileResponse, RedirectResponse
__AUTH_IMPORT__
from app.file_checks import matches
from app.storage import get_store

router = APIRouter(tags=["uploads"])

# Per field: the types, size and count it accepts (from the plan; see the app's README).
POLICIES: dict[str, dict] = __POLICIES__

MIME: dict[str, str] = __MIME__

_CHUNK = 1024 * 1024
_KEY = re.compile(r"^[a-z0-9_]+/[a-z0-9_]+/[0-9a-f]{32}/[A-Za-z0-9._-]{1,120}$")
_INLINE = {"jpg", "jpeg", "png", "webp", "gif", "avif", "pdf", "mp3", "wav", "m4a", "ogg", "mp4", "webm", "mov", "txt"}


def _safe_name(filename: str | None) -> str:
    name = (filename or "file").replace("\\\\", "/").rsplit("/", 1)[-1]
    stem, dot, ext = name.rpartition(".")
    stem = re.sub(r"[^A-Za-z0-9._-]+", "-", stem if dot else name).strip("-._") or "file"
    return f"{stem[:80]}.{ext.lower()}" if dot and ext else stem[:80]


@router.post("/uploads"__GUARD__)
async def upload_file(field: str = Form(...), file: UploadFile = File(...)) -> dict:
    policy = POLICIES.get(field)
    if policy is None:
        raise HTTPException(status_code=422, detail="unknown_field")
    name = _safe_name(file.filename)
    extension = name.rpartition(".")[2].lower() if "." in name else ""
    if extension not in policy["extensions"]:
        raise HTTPException(status_code=415, detail=f"This field accepts {policy['describe']}.")
    spooled = tempfile.SpooledTemporaryFile(max_size=8 * _CHUNK)
    size = 0
    try:
        while chunk := await file.read(_CHUNK):
            size += len(chunk)
            if size > policy["max_bytes"]:
                raise HTTPException(status_code=413, detail=f"This field accepts files up to {policy['max_bytes'] // _CHUNK} MB.")
            spooled.write(chunk)
        if size == 0:
            raise HTTPException(status_code=422, detail="The file is empty.")
        if not matches(extension, spooled):
            raise HTTPException(status_code=415, detail=f"This is not a real .{extension} file.")
        key = f"{policy['folder']}/{uuid.uuid4().hex}/{name}"
        spooled.seek(0)
        await run_in_threadpool(get_store().put, key, spooled, MIME[extension])
    finally:
        spooled.close()
    return {"key": key, "name": name, "size": size, "type": MIME[extension], "url": f"/files/{key}"}


@router.get("/files/{key:path}")
async def get_file(key: str, download: bool = Query(default=False)):
    if not _KEY.match(key):
        raise HTTPException(status_code=404, detail="not_found")
    name = key.rsplit("/", 1)[-1]
    extension = name.rpartition(".")[2].lower()
    content_type = MIME.get(extension, "application/octet-stream")
    inline = extension in _INLINE and not download
    store = get_store()
    if not await run_in_threadpool(store.exists, key):
        raise HTTPException(status_code=404, detail="not_found")
    if store.kind == "s3":
        url = await run_in_threadpool(store.signed_url, key, name, content_type, inline)
        return RedirectResponse(url, status_code=302, headers={"Cache-Control": "private, max-age=60"})
    return FileResponse(
        store.path(key),
        media_type=content_type,
        filename=name,
        content_disposition_type="inline" if inline else "attachment",
        headers={"X-Content-Type-Options": "nosniff", "Cache-Control": "private, max-age=300"},
    )
'''


