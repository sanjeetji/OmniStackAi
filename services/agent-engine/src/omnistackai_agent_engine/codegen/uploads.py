"""PC-102: file uploads in generated apps - storage, content checks, the upload window, cloud sources.

A file goes from the upload window (Uppy) to the app's API, which streams it to a temporary file
with a size cap, checks its real content against the field's policy (the first bytes, and for
Office files the parts inside the archive - never only the name), and stores it:

- S3-compatible storage when ``S3_BUCKET``/``S3_ACCESS_KEY_ID``/``S3_SECRET_ACCESS_KEY`` are set
  (Cloudflare R2 with ``S3_ENDPOINT``, or AWS S3 with ``S3_REGION``);
- otherwise the local disk (``LOCAL_STORAGE_DIR``), so an app runs with no account at all.

Files are private. ``GET /files/<key>`` answers with a short-lived signed link (S3) or the file
(local disk); keys carry a random 128-bit part, so a key is the permission to read the file.

The platform chooses the store from its own ``.env`` (``OMNISTACKAI_STORAGE_TARGET``) and passes
the generic ``S3_*`` settings to the app, so moving to production changes keys, not code
(``localrun`` and ``publish``). Cloud drives (Google Drive, Dropbox, OneDrive, Box) and web links
come through a self-hosted Uppy Companion, generated here too and started only when configured.
"""

