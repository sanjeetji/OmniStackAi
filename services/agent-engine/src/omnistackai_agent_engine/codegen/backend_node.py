def _db_repository_file(entity: Entity, workflow=None) -> str:
    tbl = table_name(entity.name)
    # R-590: the lifecycle field is never written here; a new row takes the initial state from the
    # column DEFAULT and only a transition moves it after that.
    skip = {"id", "created_at", "updated_at"} | ({workflow.field} if workflow is not None else set())
    ins_cols = [f.name for f in entity.fields if f.name not in skip]
    col_list = ", ".join(sql_identifier(f.name) for f in entity.fields)
    ins_col_list = ", ".join(sql_identifier(c) for c in ins_cols)
    placeholders = ", ".join(f"${i+1}" for i in range(len(ins_cols)))
    insert_sql = (
        f"INSERT INTO {sql_identifier(tbl)} ({ins_col_list}) VALUES ({placeholders}) RETURNING {col_list}"
        if ins_cols else f"INSERT INTO {sql_identifier(tbl)} DEFAULT VALUES RETURNING {col_list}"
    )

    return f"""// Generated by OmniStackAI: {entity.name} Repository
//
// PC-004: every call goes to PostgreSQL. This used to fall back to an in-memory Map on any database
// error and report success, so a user "saved" data that vanished on restart and nobody was told.
// A database error is now an error: the route's error handler answers 500/503 and it is logged.
import {{ pool }} from './pool.js';
import type {{ {entity.name}, Create{entity.name}Input, Update{entity.name}Input }} from '../models/types.js';

const WRITABLE: string[] = {json.dumps(ins_cols)};

export class {entity.name}Repository {{
  static async list(options: {{ limit?: number; offset?: number; search?: string }} = {{}}): Promise<{entity.name}[]> {{
    const limit = options.limit || 50;
    const offset = options.offset || 0;
    const query = 'SELECT {col_list} FROM {sql_identifier(tbl)} LIMIT $1 OFFSET $2';
    const result = await pool.query(query, [limit, offset]);
    return result.rows as {entity.name}[];
  }}

  static async getById(id: string): Promise<{entity.name} | null> {{
    const query = 'SELECT {col_list} FROM {sql_identifier(tbl)} WHERE id = $1';
    const result = await pool.query(query, [id]);
    return (result.rows[0] as {entity.name}) ?? null;
  }}

  static async create(input: Create{entity.name}Input): Promise<{entity.name}> {{
    const cols = [{", ".join(f"(input as any).{c}" for c in ins_cols)}];
    const query = `{insert_sql}`;
    const result = await pool.query(query, cols);
    return result.rows[0] as {entity.name};
  }}

  static async update(id: string, input: Update{entity.name}Input): Promise<{entity.name} | null> {{
    // Only known, writable columns: column names never come from the request (R-590).
    const keys = Object.keys(input).filter((k) => WRITABLE.includes(k));
    if (keys.length === 0) return this.getById(id);
    const setClauses = keys.map((k, idx) => `"${{k}}" = $${{idx + 2}}`).join(', ');
    const values = keys.map((k) => (input as any)[k]);
    const query = `UPDATE {sql_identifier(tbl)} SET ${{setClauses}} WHERE id = $1 RETURNING {col_list}`;
    const result = await pool.query(query, [id, ...values]);
    return (result.rows[0] as {entity.name}) ?? null;
  }}
{_node_lifecycle_setter(tbl, col_list, entity.name, workflow)}
  static async delete(id: string): Promise<boolean> {{
    const query = 'DELETE FROM {sql_identifier(tbl)} WHERE id = $1';
    const result = await pool.query(query, [id]);
    return (result.rowCount ?? 0) > 0;
  }}

  static async listBy(relationCol: string, parentId: string): Promise<{entity.name}[]> {{
    const query = `SELECT {col_list} FROM {sql_identifier(tbl)} WHERE "${{relationCol}}" = $1`;
    const result = await pool.query(query, [parentId]);
    return result.rows as {entity.name}[];
  }}
}}
"""


def _express_router_file(
    segment: str,
    apis: list[ApiEndpoint],
    repo_entities: frozenset[str],
    fk_by_entity: dict[str, tuple[str, ...]],
    has_auth: bool,
    transitions: tuple = (),
) -> str:
    lines = [
        f"// Generated by OmniStackAI: Express Router for {segment}",
        "import { Router, Request, Response } from 'express';",
    ]
    if has_auth:
        lines.append("import { requireAuth } from '../middleware/auth.js';")

    # Determine required models, repositories, and schemas
    used_entities: set[str] = set()
    for api in apis:
        wiring = wire_endpoint(api, repo_entities, fk_by_entity)
        if wiring:
            used_entities.add(wiring.entity)

    for ent in sorted(used_entities):
        lines.append(f"import {{ {ent}Repository }} from '../db/{table_name(ent)}.js';")
        lines.append(f"import {{ create{ent}Schema, update{ent}Schema }} from '../models/validation.js';")

    lines.append("")
    lines.append("export const router = Router();")
    lines.append("")

    for api in apis:
        wiring = wire_endpoint(api, repo_entities, fk_by_entity)
        method = api.method.value.lower()
        # Relative path within this segment's router
        # If api.path is /users/:id, and mounted on /api/users, rel_path is /:id
        rel = "/" + "/".join([s for s in api.path.strip("/").split("/")[1:]])
        rel_express = _to_express_path(rel)
        if not rel_express:
            rel_express = "/"

        middleware_str = "requireAuth, " if api.auth else ""

        if not wiring:
            lines.append(f"router.{method}('{rel_express}', {middleware_str}async (req: Request, res: Response) => {{")
            # PC-004: this answered 200 with a placeholder body, so a client believed the call
            # worked. It is honest now, like Python and Go, and the build report names it.
            lines.append(f"  res.status(501).json({{ detail: 'not_implemented', endpoint: '{api.method.value} {api.path}' }});")
            lines.append("});")
            lines.append("")
            continue

        ent = wiring.entity
        if wiring.op is Op.LIST:
            lines.append(f"router.{method}('{rel_express}', {middleware_str}async (req: Request, res: Response) => {{")
            lines.append("  const limit = req.query.limit ? Number(req.query.limit) : 50;")
            lines.append("  const offset = req.query.offset ? Number(req.query.offset) : 0;")
            lines.append(f"  const items = await {ent}Repository.list({{ limit, offset }});")
            lines.append("  res.json(items);")
            lines.append("});")
        elif wiring.op is Op.GET:
            param = wiring.id_param or "id"
            lines.append(f"router.{method}('{rel_express}', {middleware_str}async (req: Request, res: Response) => {{")
            lines.append(f"  const item = await {ent}Repository.getById(String(req.params.{param}));")
            lines.append("  if (!item) return res.status(404).json({ error: 'not_found', message: 'Item not found' });")
            lines.append("  res.json(item);")
            lines.append("});")
        elif wiring.op is Op.CREATE:
            lines.append(f"router.{method}('{rel_express}', {middleware_str}async (req: Request, res: Response) => {{")
            lines.append(f"  const parsed = create{ent}Schema.safeParse(req.body);")
            lines.append("  if (!parsed.success) {")
            lines.append("    return res.status(400).json({ error: 'validation_error', details: parsed.error.format() });")
            lines.append("  }")
            lines.append(f"  const created = await {ent}Repository.create(parsed.data);")
            lines.append("  res.status(201).json(created);")
            lines.append("});")
        elif wiring.op is Op.UPDATE:
            param = wiring.id_param or "id"
            lines.append(f"router.{method}('{rel_express}', {middleware_str}async (req: Request, res: Response) => {{")
            lines.append(f"  const parsed = update{ent}Schema.safeParse(req.body);")
            lines.append("  if (!parsed.success) {")
            lines.append("    return res.status(400).json({ error: 'validation_error', details: parsed.error.format() });")
            lines.append("  }")
            lines.append(f"  const updated = await {ent}Repository.update(String(req.params.{param}), parsed.data);")
            lines.append("  if (!updated) return res.status(404).json({ error: 'not_found', message: 'Item not found' });")
            lines.append("  res.json(updated);")
            lines.append("});")
        elif wiring.op is Op.DELETE:
            param = wiring.id_param or "id"
            lines.append(f"router.{method}('{rel_express}', {middleware_str}async (req: Request, res: Response) => {{")
            lines.append(f"  const ok = await {ent}Repository.delete(String(req.params.{param}));")
            lines.append("  if (!ok) return res.status(404).json({ error: 'not_found', message: 'Item not found' });")
            lines.append("  res.status(204).send();")
            lines.append("});")
        elif wiring.op is Op.LIST_BY:
            param = wiring.id_param or "id"
            fk_col = f"{wiring.relation}_id" if wiring.relation else "parent_id"
            lines.append(f"router.{method}('{rel_express}', {middleware_str}async (req: Request, res: Response) => {{")
            lines.append(f"  const items = await {ent}Repository.listBy('{fk_col}', String(req.params.{param}));")
            lines.append("  res.json(items);")
            lines.append("});")

        lines.append("")


    # R-589: lifecycle transitions. Node has requireAuth but no requireRoles, so the role is checked
    # inline against the roles the token carries; the from-state is checked the same way as in the
    # Python and Go backends. update() here already takes a partial, so no setter is needed.
    for route in transitions:
        allowed = route.transition.sources or route.workflow.states
        allowed_js = ", ".join(f"'{s}'" for s in allowed)
        param = _to_express_path(f"/{{{route.id_param}}}/{route.transition.name}")
        lines.append(f"router.post('{param}', requireAuth, async (req: Request, res: Response) => {{")
        if route.roles:
            roles_js = ", ".join(f"'{r}'" for r in route.roles)
            lines.append(f"  const held: string[] = ((req as any).user?.roles as string[] | undefined) ?? [];")
            lines.append(f"  if (![{roles_js}].some((r) => held.includes(r))) return res.status(403).json({{ error: 'forbidden' }});")
        lines.append(f"  const item = await {route.workflow.entity}Repository.getById(String(req.params.{route.id_param}));")
        lines.append("  if (!item) return res.status(404).json({ error: 'not_found', message: 'Item not found' });")
        lines.append(f"  const allowed = [{allowed_js}];")
        lines.append(f"  if (!allowed.includes((item as any).{route.workflow.field})) return res.status(409).json({{ error: 'conflict', message: `cannot {route.transition.name} from ${{(item as any).{route.workflow.field}}}; allowed from: {', '.join(allowed)}` }});")
        lines.append(f"  const updated = await {route.workflow.entity}Repository.setLifecycle(String(req.params.{route.id_param}), '{route.transition.to}');")
        lines.append("  res.json(updated);")
        lines.append("});")
        lines.append("")
    return "\n".join(lines) + "\n"


def _hono_router_file(
    segment: str,
    apis: list[ApiEndpoint],
    repo_entities: frozenset[str],
    fk_by_entity: dict[str, tuple[str, ...]],
    has_auth: bool,
    transitions: tuple = (),
) -> str:
    lines = [
        f"// Generated by OmniStackAI: Hono Router for {segment}",
        "import { Hono } from 'hono';",
    ]
    if has_auth:
        lines.append("import { requireAuth } from '../middleware/auth.js';")

    used_entities: set[str] = set()
    for api in apis:
        wiring = wire_endpoint(api, repo_entities, fk_by_entity)
        if wiring:
            used_entities.add(wiring.entity)

    for ent in sorted(used_entities):
        lines.append(f"import {{ {ent}Repository }} from '../db/{table_name(ent)}.js';")
        lines.append(f"import {{ create{ent}Schema, update{ent}Schema }} from '../models/validation.js';")

    lines.append("")
    lines.append("export const router = new Hono();")
    lines.append("")

    for api in apis:
        wiring = wire_endpoint(api, repo_entities, fk_by_entity)
        method = api.method.value.lower()
        rel = "/" + "/".join([s for s in api.path.strip("/").split("/")[1:]])
        rel_hono = _to_express_path(rel)  # Hono also uses /:id param syntax
        if not rel_hono:
            rel_hono = "/"

        middleware_str = "requireAuth, " if api.auth else ""

        if not wiring:
            lines.append(f"router.{method}('{rel_hono}', {middleware_str}async (c) => {{")
            lines.append(f"  return c.json({{ detail: 'not_implemented', endpoint: '{api.method.value} {api.path}' }}, 501);")
            lines.append("});")
            lines.append("")
            continue

        ent = wiring.entity
        if wiring.op is Op.LIST:
            lines.append(f"router.{method}('{rel_hono}', {middleware_str}async (c) => {{")
            lines.append("  const limit = c.req.query('limit') ? Number(c.req.query('limit')) : 50;")
            lines.append("  const offset = c.req.query('offset') ? Number(c.req.query('offset')) : 0;")
            lines.append(f"  const items = await {ent}Repository.list({{ limit, offset }});")
            lines.append("  return c.json(items);")
            lines.append("});")
        elif wiring.op is Op.GET:
            param = wiring.id_param or "id"
            lines.append(f"router.{method}('{rel_hono}', {middleware_str}async (c) => {{")
            lines.append(f"  const item = await {ent}Repository.getById(c.req.param('{param}') ?? '');")
            lines.append("  if (!item) return c.json({ error: 'not_found', message: 'Item not found' }, 404);")
            lines.append("  return c.json(item);")
            lines.append("});")
        elif wiring.op is Op.CREATE:
            lines.append(f"router.{method}('{rel_hono}', {middleware_str}async (c) => {{")
            lines.append("  const body = await c.req.json();")
            lines.append(f"  const parsed = create{ent}Schema.safeParse(body);")
            lines.append("  if (!parsed.success) {")
            lines.append("    return c.json({ error: 'validation_error', details: parsed.error.format() }, 400);")
            lines.append("  }")
            lines.append(f"  const created = await {ent}Repository.create(parsed.data);")
            lines.append("  return c.json(created, 201);")
            lines.append("});")
        elif wiring.op is Op.UPDATE:
            param = wiring.id_param or "id"
            lines.append(f"router.{method}('{rel_hono}', {middleware_str}async (c) => {{")
            lines.append("  const body = await c.req.json();")
            lines.append(f"  const parsed = update{ent}Schema.safeParse(body);")
            lines.append("  if (!parsed.success) {")
            lines.append("    return c.json({ error: 'validation_error', details: parsed.error.format() }, 400);")
            lines.append("  }")
            lines.append(f"  const updated = await {ent}Repository.update(c.req.param('{param}') ?? '', parsed.data);")
            lines.append("  if (!updated) return c.json({ error: 'not_found', message: 'Item not found' }, 404);")
            lines.append("  return c.json(updated);")
            lines.append("});")
        elif wiring.op is Op.DELETE:
            param = wiring.id_param or "id"
            lines.append(f"router.{method}('{rel_hono}', {middleware_str}async (c) => {{")
            lines.append(f"  const ok = await {ent}Repository.delete(c.req.param('{param}') ?? '');")
            lines.append("  if (!ok) return c.json({ error: 'not_found', message: 'Item not found' }, 404);")
            lines.append("  return c.body(null, 204);")
            lines.append("});")
        elif wiring.op is Op.LIST_BY:
            param = wiring.id_param or "id"
            fk_col = f"{wiring.relation}_id" if wiring.relation else "parent_id"
            lines.append(f"router.{method}('{rel_hono}', {middleware_str}async (c) => {{")
            lines.append(f"  const items = await {ent}Repository.listBy('{fk_col}', c.req.param('{param}') ?? '');")
            lines.append("  return c.json(items);")
            lines.append("});")

        lines.append("")


    # R-589: lifecycle transitions (see the Express router for the reasoning).
    for route in transitions:
        allowed = route.transition.sources or route.workflow.states
        allowed_js = ", ".join(f"'{s}'" for s in allowed)
        param = _to_express_path(f"/{{{route.id_param}}}/{route.transition.name}")
        lines.append(f"router.post('{param}', requireAuth, async (c) => {{")
        if route.roles:
            roles_js = ", ".join(f"'{r}'" for r in route.roles)
            lines.append("  const held: string[] = (((c as any).get('user') as any)?.roles as string[] | undefined) ?? [];")
            lines.append(f"  if (![{roles_js}].some((r) => held.includes(r))) return c.json({{ error: 'forbidden' }}, 403);")
        lines.append(f"  const item = await {route.workflow.entity}Repository.getById(c.req.param('{route.id_param}') ?? '');")
        lines.append("  if (!item) return c.json({ error: 'not_found', message: 'Item not found' }, 404);")
        lines.append(f"  const allowed = [{allowed_js}];")
        lines.append(f"  if (!allowed.includes((item as any).{route.workflow.field})) return c.json({{ error: 'conflict', message: `cannot {route.transition.name} from ${{(item as any).{route.workflow.field}}}; allowed from: {', '.join(allowed)}` }}, 409);")
        lines.append(f"  const updated = await {route.workflow.entity}Repository.setLifecycle(c.req.param('{route.id_param}') ?? '', '{route.transition.to}');")
        lines.append("  return c.json(updated);")
        lines.append("});")
        lines.append("")
    return "\n".join(lines) + "\n"


def _express_app_file(segments: list[str], has_auth: bool = False) -> str:
    lines = [
        "// Generated by OmniStackAI: Express Application",
        "import express, { Express, Request, Response, NextFunction } from 'express';",
        "import cors from 'cors';",
        "import { config } from './config.js';",
        "import { checkDbHealth } from './db/pool.js';",
    ]
    for seg in sorted(segments):
        lines.append(f"import {{ router as {seg}Router }} from './routes/{seg}.js';")
    if has_auth:
        lines.append("import { router as accountRouter } from './routes/account.js';")

    lines.append("")
    lines.append("export const app: Express = express();")
    lines.append("")
    lines.append("app.use(cors({ origin: config.corsOrigin }));")
    lines.append("app.use(express.json());")
    lines.append("")
    lines.append("// Health Check endpoints")
    lines.append("app.get(['/healthz', '/readyz', '/health'], async (req: Request, res: Response) => {")
    lines.append("  const dbOk = await checkDbHealth();")
    lines.append("  res.json({")
    lines.append("    status: 'ok',")
    lines.append("    timestamp: new Date().toISOString(),")
    lines.append("    database: dbOk ? 'connected' : 'unavailable',")
    lines.append("  });")
    lines.append("});")
    lines.append("")

    for seg in sorted(segments):
        lines.append(f"app.use('/{seg}', {seg}Router);")
    if has_auth:
        lines.append("app.use('/auth', accountRouter);  // R-591: the account flow")

    lines.append("")
    lines.append("// Global error handler")
    lines.append("app.use((err: any, req: Request, res: Response, next: NextFunction) => {")
    # PC-004: the error is logged here and never sent to the client — it used to return err.message,
    # which for a database error carries SQL and schema details.
    # A value the database cannot read (SQLSTATE class 22, e.g. a malformed id) is a 422.
    lines.append("  if (typeof err?.code === 'string' && err.code.startsWith('22')) return res.status(422).json({ detail: 'invalid_value' });")
    lines.append("  const status = err.status || 500;")
    lines.append("  if (status >= 500) console.error(err);")
    lines.append("  res.status(status).json({ detail: status >= 500 ? 'internal_error' : (err.expose ? err.message : 'request_error') });")
    lines.append("});")
    lines.append("")

    return "\n".join(lines) + "\n"


