def _auth_file(ir: ApplicationIR, framework: str) -> str:
    """The request guard. Token checks live in `auth/core.ts`, shared with the account routes.

    R-591 fixed three things here: tokens never expired (the signature was checked, `exp` never
    was), signatures were compared with `!==` rather than in constant time, and the no-token dev
    bypass fired whenever the secret merely contained 'dev-secret' — which the config supplied by
    default. The bypass now needs OMNISTACKAI_DEV_MODE=1 or a secret explicitly set to a dev value,
    and a missing secret is a 500, as in the Python and Go backends.
    """
    roles = ", ".join(f"'{role.id}'" for role in ir.roles)
    roles_type = " | ".join(f"'{role.id}'" for role in ir.roles) if ir.roles else "string"
    shared = f"""import {{ config }} from '../config.js';
import {{ verifyToken, type AuthClaims }} from '../auth/core.js';

export type {{ AuthClaims }};
export const ROLES = [{roles}] as const;
export type UserRole = {roles_type};

const DEV_SECRETS = ['local-dev-secret', 'dev-secret'];

/** Claims for the request, or an error to send. */
function authorize(header: string | undefined): {{ claims?: AuthClaims; status?: number; detail?: string }} {{
  const secret = config.jwtSecret;
  if (!header || !header.startsWith('Bearer ')) {{
    if (process.env.OMNISTACKAI_DEV_MODE === '1' || DEV_SECRETS.includes(secret)) {{
      return {{ claims: {{ sub: 'dev-admin', roles: [...ROLES], email: 'admin@example.local' }} }};
    }}
    if (!secret) return {{ status: 500, detail: 'auth_not_configured' }};
    return {{ status: 401, detail: 'unauthorized' }};
  }}
  if (!secret) return {{ status: 500, detail: 'auth_not_configured' }};
  const claims = verifyToken(header.slice(7).trim(), secret);
  if (!claims) return {{ status: 401, detail: 'invalid_token' }};
  return {{ claims }};
}}
"""
    if framework == "hono":
        return (
            "// Generated by OmniStackAI: Hono JWT Authentication Guard\n"
            "import { Context, Next } from 'hono';\n"
            + shared
            + """
export async function requireAuth(c: Context, next: Next) {
  const result = authorize(c.req.header('Authorization'));
  if (!result.claims) return c.json({ error: result.detail, detail: result.detail }, result.status as any);
  c.set('user', result.claims);
  await next();
}
"""
        )
    return (
        "// Generated by OmniStackAI: Express JWT Authentication Guard\n"
        "import { Request, Response, NextFunction } from 'express';\n"
        + shared
        + """
export interface AuthenticatedRequest extends Request {
  user?: AuthClaims;
}

export function requireAuth(req: AuthenticatedRequest, res: Response, next: NextFunction) {
  const result = authorize(req.headers.authorization);
  if (!result.claims) return res.status(result.status!).json({ error: result.detail, detail: result.detail });
  req.user = result.claims;
  next();
}
"""
    )


