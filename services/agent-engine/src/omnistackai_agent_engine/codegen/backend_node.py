_TS_TYPE: dict[FieldType, str] = {
    FieldType.STRING: "string",
    FieldType.TEXT: "string",
    FieldType.UUID: "string",
    FieldType.INT: "number",
    FieldType.FLOAT: "number",
    FieldType.BOOL: "boolean",
    FieldType.DATETIME: "Date | string",
    FieldType.JSON: "Record<string, unknown> | unknown[]",
    FieldType.ATTACHMENT: "string",
}


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-") or "app"


def _segment(path: str) -> str:
    first = path.strip("/").split("/")[0] if path.strip("/") else ""
    module = re.sub(r"\W+", "_", first).strip("_").lower()
    return module or "root"


def _pascal(value: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", value) if part)


def _camel(value: str) -> str:
    p = _pascal(value)
    return p[:1].lower() + p[1:] if p else "item"


def _path_params(path: str) -> list[str]:
    return re.findall(r"\{(\w+)\}", path)


def _to_express_path(path: str) -> str:
    # Converts /users/{id} to /users/:id
    return re.sub(r"\{(\w+)\}", r":\1", path)


def _models_file(ir: ApplicationIR) -> str:
    lines = [
        "// Generated by OmniStackAI: TypeScript Entity Models",
        "",
    ]
    if not ir.entities:
        lines.append("// No entities defined in the IR.")
        return "\n".join(lines) + "\n"

    for entity in ir.entities:
        declared_names = {f.name for f in entity.fields}
        lines.append(f"export interface {entity.name} {{")
        for field in entity.fields:
            ts_type = _TS_TYPE[field.type]
            opt = "" if field.required else "?"
            lines.append(f"  {field.name}{opt}: {ts_type};")

        # Auto audit fields if not already explicitly declared
        if "created_at" not in declared_names:
            lines.append("  created_at?: Date | string;")
        if "updated_at" not in declared_names:
            lines.append("  updated_at?: Date | string;")

        if entity.relations:
            lines.append("  // Relations")
            for rel in entity.relations:
                lines.append(f"  // {rel.name} -> {rel.target_entity} ({rel.kind.value})")

        lines.append("}")
        lines.append("")

        # Create input type (omits auto id / created_at / updated_at)
        lifecycle = next((w.field for w in workflows_of(ir) if w.entity == entity.name), None)
        if lifecycle:
            # R-590: the lifecycle field is optional on input and ignored on write.
            lines.append(
                f"export type Create{entity.name}Input = Omit<{entity.name}, 'id' | 'created_at' | 'updated_at' | '{lifecycle}'>"
                f" & {{ {lifecycle}?: string }};"
            )
        else:
            lines.append(f"export type Create{entity.name}Input = Omit<{entity.name}, 'id' | 'created_at' | 'updated_at'>;")
        lines.append(f"export type Update{entity.name}Input = Partial<Create{entity.name}Input>;")
        lines.append("")

    return "\n".join(lines) + "\n"


def _zod_field_schema(field: Field, rules: Any) -> str:
    if rules.enum:
        literals = ", ".join(f"'{v}'" for v in rules.enum)
        base = f"z.enum([{literals}])"
    elif field.type in (FieldType.STRING, FieldType.TEXT):
        base = "z.string()"
        if rules.max_length is not None:
            base += f".max({rules.max_length})"
    elif field.type is FieldType.UUID:
        base = "z.string().uuid()"
    elif field.type is FieldType.INT:
        base = "z.number().int()"
        if rules.minimum is not None:
            base += f".min({rules.minimum})"
        if rules.maximum is not None:
            base += f".max({rules.maximum})"
    elif field.type is FieldType.FLOAT:
        base = "z.number()"
        if rules.minimum is not None:
            base += f".min({rules.minimum})"
        if rules.maximum is not None:
            base += f".max({rules.maximum})"
    elif field.type is FieldType.BOOL:
        base = "z.boolean()"
    elif field.type is FieldType.DATETIME:
        base = "z.union([z.string().datetime(), z.date()])"
    elif field.type is FieldType.JSON:
        base = "z.union([z.record(z.unknown()), z.array(z.unknown())])"
    else:
        base = "z.string()"

    if not field.required:
        base += ".optional()"
    return base


def _validation_file(ir: ApplicationIR) -> str:
    lines = [
        "// Generated by OmniStackAI: Zod Validation Schemas",
        "import { z } from 'zod';",
        "",
    ]
    if not ir.entities:
        lines.append("// No entity validation required.")
        return "\n".join(lines) + "\n"

    from ..application_ir.workflow import workflows_of

    lifecycle_fields = {(w.entity, w.field) for w in workflows_of(ir)}
    for entity in ir.entities:
        lines.append(f"export const create{entity.name}Schema = z.object({{")
        for field in entity.fields:
            if field.name in ("id", "created_at", "updated_at"):
                continue
            if (entity.name, field.name) in lifecycle_fields:
                # R-590: accepted and ignored — only a transition moves the lifecycle field.
                lines.append(f"  {field.name}: z.string().optional(),")
                continue
            rules = parse_field_rules(field)
            zod_expr = _zod_field_schema(field, rules)
            lines.append(f"  {field.name}: {zod_expr},")
        lines.append("});")
        lines.append("")
        lines.append(f"export const update{entity.name}Schema = create{entity.name}Schema.partial();")
        lines.append("")

    return "\n".join(lines) + "\n"


