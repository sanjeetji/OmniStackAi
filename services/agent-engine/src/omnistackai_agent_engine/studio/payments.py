STRIPE_WEBHOOK_ROUTE_TS = """// Generated by OmniStackAI Payment Gateway: Stripe Webhook Handler
import { NextResponse } from 'next/server';
import { verifyStripeWebhookSignature } from '@/lib/payments/stripe';

// In-memory set for event idempotency (in production, persist event_id to PostgreSQL payments table)
const processedEvents = new Set<string>();

export async function POST(req: Request) {
  const secret = process.env.STRIPE_WEBHOOK_SECRET;
  if (!secret) {
    return NextResponse.json(
      { error: 'STRIPE_WEBHOOK_SECRET environment variable is missing' },
      { status: 500 }
    );
  }

  const signature = req.headers.get('stripe-signature');
  if (!signature) {
    return NextResponse.json({ error: 'Missing stripe-signature header' }, { status: 400 });
  }

  const rawBody = await req.text();
  const isValid = verifyStripeWebhookSignature(rawBody, signature, secret);

  if (!isValid) {
    return NextResponse.json({ error: 'Invalid webhook signature' }, { status: 400 });
  }

  let event: any;
  try {
    event = JSON.parse(rawBody);
  } catch {
    return NextResponse.json({ error: 'Invalid JSON payload' }, { status: 400 });
  }

  // Idempotency check: duplicate events must not double-credit or re-process
  if (processedEvents.has(event.id)) {
    return NextResponse.json({ received: true, duplicate: true }, { status: 200 });
  }
  processedEvents.add(event.id);

  if (event.type === 'checkout.session.completed') {
    const session = event.data?.object;
    // Handle successful payment, e.g. mark order as paid in database
    console.log(`[Stripe] Checkout completed for session: ${session?.id}`);
  }

  return NextResponse.json({ received: true });
}
"""

