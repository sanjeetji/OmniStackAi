STRIPE_CLIENT_TS = """// Generated by OmniStackAI Payment Gateway: Stripe Client
// Uses standard fetch and crypto (zero npm dependencies)
import crypto from 'crypto';

export interface CreateCheckoutSessionOptions {
  amount: number; // in cents/smallest currency unit
  currency?: string;
  name: string;
  description?: string;
  successUrl: string;
  cancelUrl: string;
  metadata?: Record<string, string>;
}

export interface CheckoutSessionResult {
  success: boolean;
  sessionId?: string;
  url?: string;
  error?: string;
}

export async function createCheckoutSession(
  options: CreateCheckoutSessionOptions
): Promise<CheckoutSessionResult> {
  const secretKey = process.env.STRIPE_SECRET_KEY;
  if (!secretKey) {
    return { success: false, error: 'STRIPE_SECRET_KEY environment variable is not configured' };
  }

  const currency = options.currency || 'usd';
  const params = new URLSearchParams();
  params.append('mode', 'payment');
  params.append('success_url', options.successUrl);
  params.append('cancel_url', options.cancelUrl);
  params.append('line_items[0][price_data][currency]', currency);
  params.append('line_items[0][price_data][unit_amount]', String(Math.round(options.amount)));
  params.append('line_items[0][price_data][product_data][name]', options.name);
  if (options.description) {
    params.append('line_items[0][price_data][product_data][description]', options.description);
  }
  if (options.metadata) {
    for (const [k, v] of Object.entries(options.metadata)) {
      params.append(`metadata[${k}]`, v);
    }
  }

  try {
    const res = await fetch('https://api.stripe.com/v1/checkout/sessions', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${secretKey}`,
        'Content-Type': 'application/x-www-form-urlencoded',
      },
      body: params.toString(),
    });

    const data = await res.json();
    if (!res.ok) {
      return { success: false, error: data?.error?.message || `Stripe error ${res.status}` };
    }

    return { success: true, sessionId: data.id, url: data.url };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Failed to communicate with Stripe' };
  }
}

export function verifyStripeWebhookSignature(
  payload: string,
  signatureHeader: string,
  secret: string
): boolean {
  if (!payload || !signatureHeader || !secret) {
    return false;
  }

  try {
    const parts = signatureHeader.split(',');
    let timestamp = '';
    const signatures: string[] = [];

    for (const part of parts) {
      const [k, v] = part.split('=');
      if (k === 't') timestamp = v;
      if (k === 'v1') signatures.push(v);
    }

    if (!timestamp || signatures.length === 0) {
      return false;
    }

    const signedPayload = `${timestamp}.${payload}`;
    const expected = crypto.createHmac('sha256', secret).update(signedPayload).digest('hex');

    return signatures.some((sig) => {
      if (sig.length !== expected.length) return false;
      return crypto.timingSafeEqual(Buffer.from(sig, 'utf-8'), Buffer.from(expected, 'utf-8'));
    });
  } catch {
    return false;
  }
}
"""

