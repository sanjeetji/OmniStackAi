def _git_commit(repo_dir: Path, message: str) -> None:
    """Stage and commit changes if repo_dir is inside a git repository."""
    if not (repo_dir / ".git").is_dir():
        return

    env = {
        **os.environ,
        "GIT_AUTHOR_NAME": "OmniStackAI",
        "GIT_AUTHOR_EMAIL": "agent@omnistack.ai",
        "GIT_COMMITTER_NAME": "OmniStackAI",
        "GIT_COMMITTER_EMAIL": "agent@omnistack.ai",
    }
    subprocess.run(["git", "add", "-A"], cwd=str(repo_dir), env=env, capture_output=True, text=True, check=False)
    subprocess.run(["git", "commit", "-m", message], cwd=str(repo_dir), env=env, capture_output=True, text=True, check=False)


def apply_payments(repo_dir: Path, gateway: str) -> dict[str, Any]:
    """Apply payment gateway codegen to the workspace repository and commit the changes."""
    if not repo_dir.is_dir():
        raise PaymentsError(f"repository directory does not exist: {repo_dir}")

    gateway = gateway.lower().strip()
    if gateway not in {"stripe", "razorpay"}:
        raise PaymentsError(f"unsupported payment gateway: {gateway} (must be 'stripe' or 'razorpay')")

    files_created: list[str] = []
    files_modified: list[str] = []

    # 1. lib/payments/<gateway>.ts
    payments_dir = repo_dir / "lib" / "payments"
    payments_dir.mkdir(parents=True, exist_ok=True)

    # 2. Checkout route: app/api/checkout/route.ts
    checkout_dir = repo_dir / "app" / "api" / "checkout"
    checkout_dir.mkdir(parents=True, exist_ok=True)
    checkout_file = checkout_dir / "route.ts"

    # 3. Webhook route: app/api/webhooks/<gateway>/route.ts
    webhook_dir = repo_dir / "app" / "api" / "webhooks" / gateway
    webhook_dir.mkdir(parents=True, exist_ok=True)
    webhook_file = webhook_dir / "route.ts"

    # 4. Success and cancel pages
    success_dir = repo_dir / "app" / "checkout" / "success"
    success_dir.mkdir(parents=True, exist_ok=True)
    success_file = success_dir / "page.tsx"
    success_file.write_text(SUCCESS_PAGE_TSX, encoding="utf-8")
    files_created.append("app/checkout/success/page.tsx")

    cancel_dir = repo_dir / "app" / "checkout" / "cancel"
    cancel_dir.mkdir(parents=True, exist_ok=True)
    cancel_file = cancel_dir / "page.tsx"
    cancel_file.write_text(CANCEL_PAGE_TSX, encoding="utf-8")
    files_created.append("app/checkout/cancel/page.tsx")

    # 5. Verification test
    tests_payments_dir = repo_dir / "tests" / "payments"
    tests_payments_dir.mkdir(parents=True, exist_ok=True)
    test_file = tests_payments_dir / f"test_{gateway}_webhook.js"
    test_file.write_text(SIGNATURE_VERIFY_TEST_JS, encoding="utf-8")
    files_created.append(f"tests/payments/test_{gateway}_webhook.js")

    if gateway == "stripe":
        client_file = payments_dir / "stripe.ts"
        client_file.write_text(STRIPE_CLIENT_TS, encoding="utf-8")
        files_created.append("lib/payments/stripe.ts")

        checkout_file.write_text(STRIPE_CHECKOUT_ROUTE_TS, encoding="utf-8")
        files_created.append("app/api/checkout/route.ts")

        webhook_file.write_text(STRIPE_WEBHOOK_ROUTE_TS, encoding="utf-8")
        files_created.append("app/api/webhooks/stripe/route.ts")

        # Update .env.example
        env_ex = repo_dir / ".env.example"
        env_content = env_ex.read_text(encoding="utf-8") if env_ex.is_file() else ""
        lines = [l for l in env_content.splitlines() if not l.startswith("STRIPE_") and not l.startswith("NEXT_PUBLIC_STRIPE_")]
        lines.append("STRIPE_SECRET_KEY=")
        lines.append("STRIPE_WEBHOOK_SECRET=")
        lines.append("NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY=")
        env_ex.write_text("\n".join(lines) + "\n", encoding="utf-8")
        files_modified.append(".env.example")

        _git_commit(repo_dir, "chore(payments): enable Stripe payment gateway")

        return {
            "status": "applied",
            "gateway": "stripe",
            "files_created": files_created,
            "files_modified": files_modified,
            "message": "Stripe payment gateway enabled successfully",
        }

    else:  # razorpay
        client_file = payments_dir / "razorpay.ts"
        client_file.write_text(RAZORPAY_CLIENT_TS, encoding="utf-8")
        files_created.append("lib/payments/razorpay.ts")

        checkout_file.write_text(RAZORPAY_CHECKOUT_ROUTE_TS, encoding="utf-8")
        files_created.append("app/api/checkout/route.ts")

        webhook_file.write_text(RAZORPAY_WEBHOOK_ROUTE_TS, encoding="utf-8")
        files_created.append("app/api/webhooks/razorpay/route.ts")

        # Update .env.example
        env_ex = repo_dir / ".env.example"
        env_content = env_ex.read_text(encoding="utf-8") if env_ex.is_file() else ""
        lines = [l for l in env_content.splitlines() if not l.startswith("RAZORPAY_")]
        lines.append("RAZORPAY_KEY_ID=")
        lines.append("RAZORPAY_KEY_SECRET=")
        lines.append("RAZORPAY_WEBHOOK_SECRET=")
        env_ex.write_text("\n".join(lines) + "\n", encoding="utf-8")
        files_modified.append(".env.example")

        _git_commit(repo_dir, "chore(payments): enable Razorpay payment gateway")

        return {
            "status": "applied",
            "gateway": "razorpay",
            "files_created": files_created,
            "files_modified": files_modified,
            "message": "Razorpay payment gateway enabled successfully",
        }


def remove_payments(repo_dir: Path, gateway: str) -> dict[str, Any]:
    """Remove payment gateway codegen from workspace repository and commit the deletion."""
    if not repo_dir.is_dir():
        raise PaymentsError(f"repository directory does not exist: {repo_dir}")

    gateway = gateway.lower().strip()
    if gateway not in ("stripe", "razorpay"):
        raise PaymentsError(f"unsupported payment gateway: {gateway} (must be 'stripe' or 'razorpay')")

    files_removed: list[str] = []
    files_modified: list[str] = []

    # 1. Remove lib/payments/<gateway>.ts
    client_file = repo_dir / "lib" / "payments" / f"{gateway}.ts"
    if client_file.is_file():
        client_file.unlink()
        files_removed.append(f"lib/payments/{gateway}.ts")

    # If lib/payments is now empty, remove directory
    payments_dir = repo_dir / "lib" / "payments"
    if payments_dir.is_dir() and not any(payments_dir.iterdir()):
        try:
            payments_dir.rmdir()
        except OSError:
            pass

    # 2. Remove app/api/checkout/route.ts
    checkout_route = repo_dir / "app" / "api" / "checkout" / "route.ts"
    if checkout_route.is_file():
        checkout_route.unlink()
        files_removed.append("app/api/checkout/route.ts")
        try:
            (repo_dir / "app" / "api" / "checkout").rmdir()
        except OSError:
            pass

    # 3. Remove app/api/webhooks/<gateway>
    webhook_dir = repo_dir / "app" / "api" / "webhooks" / gateway
    if webhook_dir.is_dir():
        shutil.rmtree(webhook_dir, ignore_errors=True)
        files_removed.append(f"app/api/webhooks/{gateway}")

    # 4. Remove checkout success and cancel pages
    success_page = repo_dir / "app" / "checkout" / "success" / "page.tsx"
    if success_page.is_file():
        success_page.unlink()
        files_removed.append("app/checkout/success/page.tsx")
        try:
            (repo_dir / "app" / "checkout" / "success").rmdir()
        except OSError:
            pass

    cancel_page = repo_dir / "app" / "checkout" / "cancel" / "page.tsx"
    if cancel_page.is_file():
        cancel_page.unlink()
        files_removed.append("app/checkout/cancel/page.tsx")
        try:
            (repo_dir / "app" / "checkout" / "cancel").rmdir()
        except OSError:
            pass

    try:
        (repo_dir / "app" / "checkout").rmdir()
    except OSError:
        pass

    # 5. Remove test file
    test_file = repo_dir / "tests" / "payments" / f"test_{gateway}_webhook.js"
    if test_file.is_file():
        test_file.unlink()
        files_removed.append(f"tests/payments/test_{gateway}_webhook.js")
        try:
            (repo_dir / "tests" / "payments").rmdir()
        except OSError:
            pass

    # 6. Clean .env.example
    env_ex = repo_dir / ".env.example"
    if env_ex.is_file():
        env_content = env_ex.read_text(encoding="utf-8")
        prefix = "STRIPE_" if gateway == "stripe" else "RAZORPAY_"
        lines = [
            l for l in env_content.splitlines()
            if not l.startswith(prefix) and not (gateway == "stripe" and l.startswith("NEXT_PUBLIC_STRIPE_"))
        ]
        env_ex.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")
        files_modified.append(".env.example")

    _git_commit(repo_dir, f"chore(payments): disable {gateway} payment gateway")

    return {
        "status": "removed",
        "gateway": gateway,
        "files_removed": files_removed,
        "files_modified": files_modified,
        "message": f"{gateway.capitalize()} payment gateway disabled and code removed",
    }
