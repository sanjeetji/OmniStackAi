"""PC-008: the production bundle — what a generated project needs to run in production, anywhere.

Written into the project itself (and committed), so the owner is never tied to OmniStackAI to run
what they built: `docker compose -f deploy/compose.yaml --env-file <secrets> up -d` on any machine
with Docker starts the whole app — a dedicated PostgreSQL, the API, the web app, the admin console
and one entry point in front of them:

    /         the web app
    /admin    the admin console (built with that base path)
    /api/...  the API (the prefix is removed, exactly as the Studio preview proxy does)

The entry point is Caddy (open source). Given a real domain it obtains and renews HTTPS
certificates on its own; without one it serves plain HTTP on a local port — the stand-in used
until a server and domain are supplied (PC-070).

Every file here is deterministic for a given project layout, and nothing secret is written: the
database password and signing secret live in an env file outside the project (see `stack.py`).
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

WEB_PORT = 3000
API_PORT = 8000


@dataclass(frozen=True)
class Layout:
    """Which parts a project has, read from its files (edits can add or remove parts)."""

    slug: str
    api_kind: str | None  # "python" | "go" | "node" | None
    web_apps: tuple[str, ...]  # "web" first, then "admin", then any role surfaces

    @property
    def has_admin(self) -> bool:
        return "admin" in self.web_apps


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:40] or "app"


def _is_next_app(app_dir: Path) -> bool:
    """A Next.js web surface, known by its dependencies (an Expo app may carry no app.json)."""
    try:
        manifest = json.loads((app_dir / "package.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    deps = {**(manifest.get("dependencies") or {}), **(manifest.get("devDependencies") or {})}
    return "next" in deps and "expo" not in deps


def read_layout(repo: Path, slug: str) -> Layout:
    api = repo / "services" / "api"
    api_kind = (
        "python" if (api / "requirements.txt").is_file()
        else "go" if (api / "go.mod").is_file()
        else "node" if (api / "package.json").is_file()
        else None
    )
    apps = sorted(
        (p.parent.name for p in (repo / "apps").glob("*/package.json") if _is_next_app(p.parent)),
        key=lambda name: (name != "web", name != "admin", name),
    )
    return Layout(slug=_slug(slug), api_kind=api_kind, web_apps=tuple(apps))


def base_path(app: str) -> str:
    return "" if app == "web" else f"/{app}"


# ── Dockerfiles ───────────────────────────────────────────────────────────────────────────────────

NEXT_DOCKERFILE = f"""\
# Production image for this Next.js app (generated by OmniStackAI; safe to edit).
# Built from the project root: the app imports the shared brand files there (brand.json, brand/).
FROM node:22-bookworm-slim AS build
ARG APP=web
WORKDIR /repo/apps/$APP
RUN corepack enable && corepack prepare pnpm@9.15.0 --activate
ENV npm_config_store_dir=/pnpm-store NEXT_TELEMETRY_DISABLED=1
COPY apps/$APP/package.json ./
RUN pnpm install --ignore-scripts
COPY . /repo
# Baked in at build time: where the browser finds the API, and the path this app is served under.
ARG NEXT_PUBLIC_API_URL=/api
ARG BASE_PATH=
ENV NEXT_PUBLIC_API_URL=$NEXT_PUBLIC_API_URL BASE_PATH=$BASE_PATH
RUN pnpm build

FROM node:22-bookworm-slim
ARG APP=web
ARG BASE_PATH=
WORKDIR /app
ENV NODE_ENV=production NEXT_TELEMETRY_DISABLED=1 BASE_PATH=$BASE_PATH
COPY --from=build /repo/apps/$APP ./
EXPOSE {WEB_PORT}
CMD ["node_modules/.bin/next", "start", "-p", "{WEB_PORT}"]
"""

PYTHON_DOCKERFILE = f"""\
# Production image for this FastAPI service (generated by OmniStackAI; safe to edit).
FROM python:3.12-slim
WORKDIR /app
ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PIP_DISABLE_PIP_VERSION_CHECK=1
COPY requirements.txt ./
RUN pip install --no-cache-dir -r requirements.txt
COPY . .
EXPOSE {API_PORT}
CMD ["uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", "{API_PORT}", "--proxy-headers", "--forwarded-allow-ips", "*"]
"""

GO_DOCKERFILE = f"""\
# Production image for this Go service (generated by OmniStackAI; safe to edit).
FROM golang:1.23-bookworm AS build
WORKDIR /src
COPY . .
RUN go mod tidy && CGO_ENABLED=0 go build -trimpath -o /server .

FROM debian:bookworm-slim
RUN apt-get update && apt-get install -y --no-install-recommends ca-certificates && rm -rf /var/lib/apt/lists/*
COPY --from=build /server /server
ENV PORT={API_PORT} ADDR=:{API_PORT}
EXPOSE {API_PORT}
CMD ["/server"]
"""

